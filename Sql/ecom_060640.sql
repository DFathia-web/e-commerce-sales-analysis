-- total refund colllected per customers
select count(distinct refund_amount) as count_of_refund, customer_id from e.`sales-analysis`
group by customer_id
order by count_of_refund desc;

-- average revenue generated per  and the customer segment
select customer_id, customer_segment, sum(net_revenue) as total_net_revenue from e.`sales-analysis`
group by customer_segment, customer_id
order by total_net_revenue desc;
with total_net_revenue as (
select customer_id, customer_segment, sum(net_revenue) as total_net_revenue from e.`sales-analysis`
group by customer_segment, customer_id
order by total_net_revenue desc
)
select customer_id, customer_segment, avg(total_net_revenue) as average_net_revenue from total_net_revenue
group by customer_segment, customer_id
order by average_net_revenue ; 

-- orders per customer and the acquisition channel
select acquisition_channel, customer_id, count(distinct order_id)as count_of_orders from e.`sales-analysis`
group by acquisition_channel, customer_id
order by count_of_orders;
with count_of_orders as (
select acquisition_channel, customer_id, count(distinct order_id)as count_of_orders from e.`sales-analysis`
group by acquisition_channel, customer_id
order by count_of_orders
)
select acquisition_channel, sum(count_of_orders) as sum_of_orders from count_of_orders
group by acquisition_channel
order by sum_of_orders;

select customer_id, sum(net_revenue) as total_net_revenue from e.`sales-analysis`
group by customer_id
having total_net_revenue > (
select avg(total_net_revenue)
from (
select customer_id, sum(net_revenue) as total_net_revenue from e.`sales-analysis`
group by customer_id) as total_net_revenue
)
order by total_net_revenue desc;

-- total revenue per order
select order_id, sum(net_revenue) as total_net_revenue from e.`sales-analysis`
group by order_id
having sum(net_revenue) > (
select avg(total_net_revenue)
from(
select order_id, sum(net_revenue) as total_net_revenue from e.`sales-analysis`
group by order_id) as total_net_revenue
)
order by total_net_revenue desc;
-- top 10 customers with highest net_revenue
select customer_id, sum(net_revenue) as total_net_revenue from e.`sales-analysis`
group by customer_id
order by total_net_revenue desc
limit 10;

select month, year, sum(net_revenue) from e.`sales-analysis`
group by month, year;

-- country with highest repeating customers
select country_code, customer_id, count(order_id) as order_count from e.`sales-analysis`
group by country_code, customer_id;
with order_count as ( 
select country_code, customer_id, count(order_id) as order_count from e.`sales-analysis`
group by country_code, customer_id)
select country_code, sum(order_count) as order_sum from order_count
group by country_code
order by order_sum;
-- customer and customer segment rank by revenue
select customer_id, customer_segment, sum(net_revenue) as total_net_revenue, 
rank() over(
partition by customer_segment
order by sum(net_revenue) desc) as revenue_rank from e.`sales-analysis`
group by customer_id, customer_segment
order by customer_segment, revenue_rank;

-- revenue percent by country
select country_code, sum(net_revenue) as country_revenue, 
sum(net_revenue)/ (select sum(net_revenue) from e.`sales-analysis`) * 100 as revenue_percentage
from e.`sales-analysis`
group by country_code
order by revenue_percentage desc;
