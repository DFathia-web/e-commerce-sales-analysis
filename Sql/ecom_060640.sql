-- checking if data is complete and checking for duplicates
select * from e.`sales-analysis`;
select count(order_id),
count(customer_id),
count(net_revenue) from e.`sales-analysis`;
select order_id, count(*) as orders from e.`sales-analysis`
group by order_id
having count(*)>1;

-- revenue, total orders by country
select country_code, sum(net_revenue) as total_net_income from e.`sales-analysis`
group by country_code;
select country_code, count(customer_id) as customer_ids from e.`sales-analysis`
group by country_code;
select country_code, count(distinct order_id) as total_orders from e.`sales-analysis`
group by country_code
order by total_orders DESC;


-- repeat customers
select customer_id, count(*) as number_of_orders from e.`sales-analysis`
group by customer_id
having count(*)>1;
select customer_id, count(*) as orders, sum(net_revenue)as total_net_revenue from e.`sales-analysis`
group by customer_id
having count(*)>1;
select customer_id, count(distinct order_id) as order_count, sum(net_revenue)as total_net_revenue from e.`sales-analysis`
group by customer_id
having count(distinct order_id)>1;


-- total_orders by customer_segment 
select customer_segment, count(distinct order_id) as order_ids from e.`sales-analysis`
group by customer_segment
order by order_ids DESC;
-- total_net_revenue by customer_segment
select customer_segment, sum(net_revenue) as total_net_revenue from e.`sales-analysis`
group by customer_segment;

-- total_orders by aquisition channel
select acquisition_channel, count(distinct order_id) as orders from e.`sales-analysis`
group by acquisition_channel
order by order_ids DESC;

-- total revenue by customer segment and acquisition channel
select customer_segment, acquisition_channel, sum(net_revenue)as total_net_revenue from e.`sales-analysis`
